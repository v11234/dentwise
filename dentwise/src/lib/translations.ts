function getNestedValue(dictionary: Dictionary, key: string) {
  const parts = key.split(".");
  let current: DictionaryValue | undefined = dictionary;
  for (const part of parts) {
    if (!current || typeof current === "string") return undefined;
    current = current[part];
  }
  return typeof current === "string" ? current : undefined;
}

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return Object.entries(vars).reduce((acc, [key, value]) => {
    return acc.replace(new RegExp(`\\{${key}\\}`, "g"), String(value));
  }, template);
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const primary = getNestedValue(translations[locale], key);
  const fallback = getNestedValue(translations[DEFAULT_LOCALE], key);
  const template = primary || fallback || key;
  return interpolate(template, vars);
}

